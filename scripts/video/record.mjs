// Records scripts/video/walkthrough.html in real time and encodes public/media/automation-walkthrough.mp4 (and a poster).
import { chromium } from 'playwright';
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(import.meta.dirname, '../..');
const tmp = process.argv[2] ?? '/tmp/fw-video';
fs.rmSync(tmp, { recursive: true, force: true }); fs.mkdirSync(tmp, { recursive: true });
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1280, height: 720 }, recordVideo: { dir: tmp, size: { width: 1280, height: 720 } } });
const p = await ctx.newPage();
await p.goto('file://' + path.join(root, 'scripts/video/walkthrough.html'));
await p.waitForFunction(() => window.__done === true, null, { timeout: 90000, polling: 500 });
await p.waitForTimeout(300);
await ctx.close(); await b.close();
const webm = fs.readdirSync(tmp).find((f) => f.endsWith('.webm'));
fs.mkdirSync(path.join(root, 'public/media'), { recursive: true });
const out = path.join(root, 'public/media/automation-walkthrough.mp4');
execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-i', path.join(tmp, webm), '-ss', '0.7', '-r', '30', '-c:v', 'libx264', '-preset', 'slow', '-crf', '26', '-pix_fmt', 'yuv420p', '-movflags', '+faststart', '-an', out]);
execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-ss', '1.8', '-i', out, '-frames:v', '1', '-q:v', '4', path.join(root, 'public/media/automation-walkthrough-poster.jpg')]);
console.log(fs.statSync(out).size, 'bytes');
execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-i', out, '-c:v', 'libvpx-vp9', '-b:v', '0', '-crf', '36', '-row-mt', '1', '-an', out.replace('.mp4', '.webm')]);
